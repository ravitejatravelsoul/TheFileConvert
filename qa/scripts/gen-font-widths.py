"""Regenerates src/lib/processors/pdf-to-word/fontWidths.ts from the bundled open fonts.

    python qa/scripts/gen-font-widths.py

Advance widths (1/1000 em) for the characters scanned-page typography is estimated from (scanPage.ts). Each
family is an open font metric-compatible with a common document font, so a word's measured width gives the
same size in the font Word will use:
  serif   Liberation Serif  ≙ Times New Roman     sans     Liberation Sans ≙ Arial
  mono    Liberation Mono   ≙ Courier New         georgia  Gelasio         ≙ Georgia
  calibri Carlito           ≙ Calibri             cambria  Caladea         ≙ Cambria
"""
import json
import os

from fontTools.ttLib import TTFont

FONTS = os.path.join("public", "fonts", "word")
OUT = os.path.join("src", "lib", "processors", "pdf-to-word", "fontWidths.ts")
CHARS = (
    " !\"#$%&'()*+,-./0123456789:;<=>?@ABCDEFGHIJKLMNOPQRSTUVWXYZ[\\]^_`abcdefghijklmnopqrstuvwxyz{|}~"
    "€£¥–—‘’“”•…©®°±×÷½¼¾áéíóúñüöäçàèâêôÁÉÍÓÚÑ"
)
TABLES = [
    ("serif", "serif-r"), ("serifBold", "serif-b"),
    ("sans", "sans-r"), ("sansBold", "sans-b"),
    ("mono", "mono-r"),
    ("georgia", "gelasio-r"), ("georgiaBold", "gelasio-b"),
    ("calibri", "carlito-r"), ("calibriBold", "carlito-b"),
    ("cambria", "caladea-r"), ("cambriaBold", "caladea-b"),
]


def widths(path):
    f = TTFont(path)
    cmap = f.getBestCmap()
    hmtx = f["hmtx"]
    upm = f["head"].unitsPerEm
    space = hmtx[cmap[32]][0]
    return [round(hmtx[cmap.get(ord(c), cmap[32])][0] * 1000 / upm) if ord(c) in cmap else round(space * 1000 / upm) for c in CHARS]


# Caladea is sold as metric-compatible with Cambria, but the Cambria Windows and Word ship is wider (measured:
# 6.4 % regular, 3.9 % bold over the character table) — a word's measured width would read as a larger size.
# Its table is scaled by the ratio, measured against the installed Cambria when present (no Cambria data is
# copied, only this one number per style).
SCALE_REF = {"cambria": ("C:/Windows/Fonts/cambria.ttc", "caladea-r", 1.064), "cambriaBold": ("C:/Windows/Fonts/cambriab.ttf", "caladea-b", 1.039)}


def scale_for(name):
    if name not in SCALE_REF:
        return 1.0
    path, ours, fallback = SCALE_REF[name]
    if not os.path.exists(path):
        return fallback
    from fontTools.ttLib import TTCollection
    real = TTCollection(path).fonts[0] if path.endswith(".ttc") else TTFont(path)
    mine = TTFont(os.path.join(FONTS, ours + ".ttf"))
    def total(f):
        cmap, hm = f.getBestCmap(), f["hmtx"]
        return sum(hm[cmap[ord(c)]][0] for c in CHARS if ord(c) in cmap) / f["head"].unitsPerEm
    return round(total(real) / total(mine), 4)


rows = []
for name, file in TABLES:
    k = scale_for(name)
    rows.append(f"  {name}: [{','.join(str(round(v * k)) for v in widths(os.path.join(FONTS, file + '.ttf')))}],")


def heights(path):
    f = TTFont(path)
    o = f["OS/2"]
    upm = f["head"].unitsPerEm
    return round(o.sxHeight / upm, 3), round(o.sCapHeight / upm, 3)


metric_rows = []
for name, file in TABLES:
    xh, ch = heights(os.path.join(FONTS, file + ".ttf"))
    metric_rows.append(f"  {name}: {{ xHeight: {xh}, capHeight: {ch} }},")
names = " | ".join(json.dumps(n) for n, _ in TABLES)
src = f"""// Advance widths (1/1000 em) of the bundled open fonts, for estimating a scanned word's font and size
// from its measured width (scanPage.ts). Generated by qa/scripts/gen-font-widths.py from public/fonts/word/*.ttf
// (Liberation 2.1.5, Gelasio, Carlito, Caladea — SIL OFL; each metric-compatible with a common document font).
export const WIDTH_CHARS = {json.dumps(CHARS, ensure_ascii=False)};
export const WIDTHS: Record<{names}, number[]> = {{
{chr(10).join(rows)}
}};
/** x-height and cap height (in em) of the same fonts, from their OS/2 tables. */
export const HEIGHTS: Record<{names}, {{ xHeight: number; capHeight: number }}> = {{
{chr(10).join(metric_rows)}
}};
"""
open(OUT, "w", encoding="utf8", newline="\n").write(src)
print(OUT, len(CHARS), "chars,", len(TABLES), "tables")
